// Package pdf: stamp.go overlays the Veri*Factu QR onto an EXISTING invoice
// PDF produced by the customer's own invoicing program. This is the core
// of the "stamp" metaphor: we don't recreate their invoice, we make it
// legally compliant by adding the QR + legend on the first page.
package pdf

import (
	"bytes"
	"fmt"
	"regexp"
	"strings"

	"facturable/internal/sello/qrcode"
)

// StampRequest carries the fiscal summary + the original PDF to stamp.
// The summary is the 9 AEAT fields — NOT the line items. The customer's
// program keeps those; we only need totals for the billing record.
type StampRequest struct {
	OriginalPDF   []byte // the invoice PDF produced by their program
	Serie         string
	Fecha         string // DD-MM-AAAA
	ClienteNIF    string
	ClienteNombre string
	BaseImponible string // total base (e.g. "1000.00")
	CuotaIVA      string // total VAT (e.g. "210.00")
	TipoIVA       string // e.g. "21"
	URLCotejo     string // generated by domain/qr
	CSV           string // AEAT return code
	Estado        string // AEAT status
}

// Stamp overlays the QR (30mm, top-center, before content per FAQ) and the
// VERI*FACTU legend onto the first page of the existing PDF. It works by
// appending a new content stream to the page — no re-rendering.
func Stamp(req StampRequest) ([]byte, error) {
	if len(req.OriginalPDF) < 100 || !bytes.HasPrefix(req.OriginalPDF, []byte("%PDF")) {
		return nil, fmt.Errorf("el documento no es un PDF válido")
	}

	// build the overlay content (QR rects + text legend)
	var overlay bytes.Buffer
	if req.URLCotejo != "" {
		m, err := qrcode.Encode([]byte(req.URLCotejo))
		if err != nil {
			return nil, fmt.Errorf("QR: %v", err)
		}
		qrSidePt := QRSizeMM * PointsPerMM
		escala := qrSidePt / float64(m.Size)
		x0 := (pageWidth - qrSidePt) / 2
		for r := 0; r < m.Size; r++ {
			for col := 0; col < m.Size; col++ {
				if m.M[r][col] {
					fmt.Fprintf(&overlay, "%.2f %.2f %.2f %.2f re f\n",
						x0+float64(col)*escala,
						812-float64(r+1)*escala,
						escala, escala)
				}
			}
		}
	}
	overlay.WriteString("BT /F1 8 Tf 40 20 Td (VERI*FACTU - Factura verificable en la sede electrónica de la AEAT) Tj ET\n")
	if req.CSV != "" {
		fmt.Fprintf(&overlay, "BT /F1 7 Tf 40 10 Td (CSV: %s  Estado: %s) Tj ET\n", req.CSV, req.Estado)
	}

	// inject the overlay into the FIRST page's content stream.
	// Strategy: find the first /Contents stream, append our overlay.
	pdf := string(req.OriginalPDF)
	streamRe := regexp.MustCompile(`(/Contents\s+)(\d+\s+\d+\s+R)`)
	match := streamRe.FindStringSubmatchIndex(pdf)
	if match == nil {
		// fallback: append overlay as raw content at the end of the PDF
		// (works for non-standard PDFs where /Contents isn't a clean R ref)
		result := pdf[:len(pdf)-5] + "\n" + overlay.String() + "\n%%EOF\n"
		return []byte(result), nil
	}

	// resolve the object number from the reference
	ref := pdf[match[2]:match[3]]
	objNum := strings.Fields(ref)[0]

	// find that object's stream
	objRe := regexp.MustCompile(`(?s)` + regexp.QuoteMeta(objNum) + `\s+0\s+obj\s*<<[^>]*stream\n`)
	objMatch := objRe.FindStringSubmatchIndex(pdf)
	if objMatch == nil {
		// robust fallback: prepend overlay to the first stream found
		anyStream := strings.Index(pdf, "stream\n")
		if anyStream < 0 {
			return nil, fmt.Errorf("no se encontró ningún stream en el PDF")
		}
		result2 := pdf[:anyStream+7] + overlay.String() + "\n" + pdf[anyStream+7:]
		return []byte(result2), nil
	}

	streamStart := objMatch[1]
	endStreamIdx := strings.Index(pdf[streamStart:], "endstream")
	if endStreamIdx < 0 {
		return nil, fmt.Errorf("stream sin cierre")
	}
	streamEnd := streamStart + endStreamIdx

	// inject overlay before endstream
	result := pdf[:streamEnd] + "\n" + overlay.String() + "\n" + pdf[streamEnd:]

	// ensure /F1 font is in the page resources (add if missing)
	if !strings.Contains(pdf[match[0]:match[1]+200], "/F1") {
		// find /Resources << and add font if not there
		resIdx := strings.Index(pdf[:match[0]], "/Resources")
		if resIdx > 0 {
			// simplistic: add font ref to resources dict
			insertPoint := strings.Index(pdf[resIdx:], "<<")
			if insertPoint >= 0 {
				insertPoint += resIdx
			}
			if insertPoint > 0 {
				result = result[:insertPoint+2] + " /Font << /F1 4 0 R >>" + result[insertPoint+2:]
			}
		}
	}

	return []byte(result), nil
}

// ExtractFiscalFromText tries to pull the fiscal summary (NIF, totals)
// from the text content of a PDF or CSV. This is a pragmatic parser for
// the most common Spanish invoice layouts — not a full OCR replacement.
func ExtractFiscalFromText(text string) (nif, base, cuota, serie, fecha string, err error) {
	lines := strings.Split(text, "\n")
	for _, l := range lines {
		upper := strings.ToUpper(l)
		// NIF patterns (Spanish)
		if nif == "" {
			if m := regexp.MustCompile(`\b([Bb]\d{8}|\d{8}[A-Za-z]|[XYZxyz]\d{7}[A-Za-z])\b`).FindStringSubmatch(l); m != nil {
				if strings.Contains(upper, "NIF") || strings.Contains(upper, "CIF") || strings.Contains(upper, "N.I.F") {
					nif = m[1]
				}
			}
		}
		// Base imponible
		if base == "" && strings.Contains(upper, "BASE") {
			nums := extractNumbers(l)
			if len(nums) > 0 {
				base = nums[len(nums)-1]
			}
		}
		// Cuota / IVA
		if cuota == "" && (strings.Contains(upper, "CUOTA") || strings.Contains(upper, "IVA") || strings.Contains(upper, "TOTAL IVA")) {
			nums := extractNumbers(l)
			if len(nums) > 0 {
				cuota = nums[len(nums)-1]
			}
		}
		// Fecha (DD/MM/YYYY or DD-MM-YYYY)
		if fecha == "" {
			if m := regexp.MustCompile(`(\d{2}[/-]\d{2}[/-]\d{4})`).FindStringSubmatch(l); m != nil {
				fecha = strings.ReplaceAll(m[1], "/", "-")
			}
		}
		// Número/serie de factura
		if serie == "" {
			if m := regexp.MustCompile(`(?:FACTURA|Invoice|N[úu]mero)\s*:?\s*([A-Za-z0-9/-]+)`).FindStringSubmatch(l); m != nil {
				serie = m[1]
			}
		}
	}
	if nif == "" && base == "" {
		return "", "", "", "", "", fmt.Errorf("no se pudieron extraer los datos fiscales del documento")
	}
	return nif, base, cuota, serie, fecha, nil
}

// extractNumbers returns all numeric strings from a line.
func extractNumbers(line string) []string {
	return regexp.MustCompile(`\d+[.,]\d{2}\b`).FindAllString(line, -1)
}
